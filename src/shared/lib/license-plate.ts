/**
 * Казахстанский госномер: нормализация ввода и проверка.
 *
 * Формат (согласован с заказчиком 2026-08-29): 3 цифры + 2–3 буквы + 2 цифры
 * региона, например `577AXG02` или `777II02`. Регион — существующий код 01–20.
 *
 * Раньше проверка была почти никакая (`^[A-ZА-ЯЁ0-9\-\s]{2,32}$`), и в гараж
 * проходили огрызки вроде `577AXG` без региона.
 *
 * Нормализация обязательна перед проверкой: люди набирают номер с пробелами
 * и дефисами, а на кириллической раскладке — русскими буквами, визуально
 * неотличимыми от латинских. `А` (U+0410) и `A` (U+0041) выглядят одинаково,
 * но это разные символы, и без подмены валидный номер отвергался бы.
 */

/** Кириллические буквы, совпадающие по начертанию с латинскими. */
const CYRILLIC_TO_LATIN: Record<string, string> = {
  А: 'A', В: 'B', Е: 'E', К: 'K', М: 'M', Н: 'H', О: 'O',
  Р: 'P', С: 'C', Т: 'T', У: 'Y', Х: 'X', І: 'I', Ё: 'E',
}

/** Приводит ввод к каноническому виду: без разделителей, верхний регистр, латиница. */
export function normalizeLicensePlate(raw: string): string {
  return raw
    .toUpperCase()
    .replace(/[\s\-_]/g, '')
    .split('')
    .map((ch) => CYRILLIC_TO_LATIN[ch] ?? ch)
    .join('')
}

/** 3 цифры + 2–3 латинские буквы + регион 01–20. */
export const LICENSE_PLATE_REGEX = /^\d{3}[A-Z]{2,3}(?:0[1-9]|1\d|20)$/

export function isValidLicensePlate(raw: string): boolean {
  return LICENSE_PLATE_REGEX.test(normalizeLicensePlate(raw))
}

export const LICENSE_PLATE_ERROR =
  'Введите номер полностью, вместе с регионом. Например: 123ABC02'
